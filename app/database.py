def init_db(seed: bool = True) -> None:
    Path(DATABASE_PATH).parent.mkdir(parents=True, exist_ok=True)
    with get_connection() as conn:
        conn.executescript(SCHEMA)
        if seed:
            seed_demo_data(conn)


